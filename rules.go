package main

import (
	"fmt"
	"net/netip"
	"strings"
)

// anthropicRanges are Anthropic's published inbound and outbound ranges:
// https://platform.claude.com/docs/en/api/ip-addresses
// claude.ai, api.anthropic.com and the Claude Code endpoints all live here.
var anthropicRanges = []string{
	"160.79.104.0/21",
	"153.61.208.0/20",
	"153.61.224.0/22",
	"2607:6bc0::/48",
}

const (
	pfAnchor     = "com.apple/claudeguard"
	winRuleGroup = "claudeguard"
	winRuleName  = "claudeguard: block direct traffic to Anthropic"
)

// FirewallOptions describe the kill switch rules. They are passed on the
// command line (not read from the user's config) because the rules are
// applied as root/Administrator.
type FirewallOptions struct {
	AllowTunnels bool
	Extra        []string
}

func (o FirewallOptions) ranges() []string {
	return append(append([]string{}, anthropicRanges...), o.Extra...)
}

func (o FirewallOptions) args() []string {
	var a []string
	if o.AllowTunnels {
		a = append(a, "--allow-tunnels")
	}
	if len(o.Extra) > 0 {
		a = append(a, "--extra-block", strings.Join(o.Extra, ","))
	}
	return a
}

func parseCIDRList(s string) ([]string, error) {
	var out []string
	for _, p := range strings.Split(s, ",") {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		// Written back in canonical form: pf and PowerShell must read the
		// same network we validated.
		if pfx, err := netip.ParsePrefix(p); err == nil {
			p = pfx.Masked().String()
		} else if ip, err := netip.ParseAddr(p); err == nil && ip.Zone() == "" {
			p = ip.Unmap().String()
		} else {
			return nil, fmt.Errorf("not an IP or CIDR: %q", p)
		}
		out = append(out, p)
	}
	return out, nil
}

// renderPFRules builds the pf anchor. Everything bound for Anthropic is
// rejected unless it leaves through one of the allowed tunnel interfaces.
// Traffic to the proxy itself is untouched, so the proxy is the only way out.
func renderPFRules(ranges, tunnels []string) string {
	var b strings.Builder
	b.WriteString("# Generated by claudeguard. Direct traffic to Anthropic is rejected;\n")
	b.WriteString("# only the proxy (or an allowed VPN tunnel) can reach it.\n")
	fmt.Fprintf(&b, "table <claudeguard> const { %s }\n", strings.Join(ranges, ", "))
	for _, ifc := range tunnels {
		// if-bound: when the VPN drops, its states must not carry on over en0.
		fmt.Fprintf(&b, "pass out quick on %s to <claudeguard> keep state (if-bound)\n", ifc)
	}
	b.WriteString("block return out quick to <claudeguard>\n")
	return b.String()
}

func psQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// windowsFirewallScript replaces the claudeguard rule group with a single
// outbound block rule. Block rules win over allow rules in Windows Firewall.
// With AllowTunnels the rule only covers physical adapters, so a VPN adapter
// (Wintun, TAP, RAS) can still carry the traffic.
func windowsFirewallScript(o FirewallOptions) string {
	var addrs []string
	for _, r := range o.ranges() {
		addrs = append(addrs, psQuote(r))
	}
	iface := ""
	var b strings.Builder
	b.WriteString("$ErrorActionPreference = 'Stop'\n")
	if o.AllowTunnels {
		b.WriteString("$phys = @(Get-NetAdapter -Physical | ForEach-Object Name)\n")
		b.WriteString("if (-not $phys) { throw 'no physical network adapters found' }\n")
		iface = " -InterfaceAlias $phys"
	}
	fmt.Fprintf(&b, "Get-NetFirewallRule -Group %s -ErrorAction SilentlyContinue | Remove-NetFirewallRule\n", psQuote(winRuleGroup))
	fmt.Fprintf(&b, "New-NetFirewallRule -DisplayName %s -Group %s -Direction Outbound -Action Block -Profile Any -RemoteAddress @(%s)%s | Out-Null\n",
		psQuote(winRuleName), psQuote(winRuleGroup), strings.Join(addrs, ","), iface)
	b.WriteString("$off = Get-NetFirewallProfile | Where-Object { -not $_.Enabled } | ForEach-Object Name\n")
	b.WriteString("if ($off) { Write-Warning ('Windows Firewall is OFF for profiles: ' + ($off -join ', ') + '. The kill switch does not work there.') }\n")
	return b.String()
}

func windowsRemoveScript() string {
	return fmt.Sprintf("Get-NetFirewallRule -Group %s -ErrorAction SilentlyContinue | Remove-NetFirewallRule\n", psQuote(winRuleGroup))
}
